/**
 * Represents the state of keyboard inputs for controlling the game.
 */
class Keyboard {
  /** @type {boolean} Indicates if the left arrow key is pressed. */
  LEFT = false;

  /** @type {boolean} Indicates if the right arrow key is pressed. */
  RIGHT = false;

  /** @type {boolean} Indicates if the up arrow key is pressed. */
  UP = false;

  /** @type {boolean} Indicates if the down arrow key is pressed. */
  DOWN = false;

  /** @type {boolean} Indicates if the spacebar is pressed. */
  SPACE = false;

  /** @type {boolean} Indicates if the 'D' key is pressed. */
  D = false;

  /** @type {boolean} Indicates if the 'A' key is pressed. */
  A = false;

  /** @type {boolean} Indicates if the 'S' key is pressed. */
  S = false;

  /** @type {boolean} Indicates if the '1' key is pressed. */
  ONE = false;

  /** @type {boolean} Indicates if the '2' key is pressed. */
  TWO = false;
}
